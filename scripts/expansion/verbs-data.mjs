/** @param {string} infinitive @param {1|2|3} difficulty @param {'regular'|'ieren'} pattern */
function regular(infinitive, stem, difficulty, pattern = 'regular') {
  const du = stem.endsWith('z') || stem.endsWith('s') || stem.endsWith('ß') ? `${stem}t` : `${stem}st`
  const er = `${stem}t`
  const ihr = `${stem}t`
  return {
    infinitive,
    pattern,
    difficulty,
    forms: { ich: `${stem}e`, du, er, wir: infinitive, ihr, sie: infinitive },
  }
}

function iere(infinitive, difficulty) {
  const base = infinitive.replace(/en$/, '')
  return {
    infinitive,
    pattern: 'ieren',
    difficulty,
    forms: {
      ich: `${base}e`,
      du: `${base}st`,
      er: `${base}t`,
      wir: infinitive,
      ihr: `${base}t`,
      sie: infinitive,
    },
  }
}

