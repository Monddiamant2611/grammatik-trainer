const byArea = new Map(modules.map((module) => [module.area, module]))

export function foundationModule(area: AreaId): FoundationModule {
  const module = byArea.get(area)
  if (!module) throw new Error(`Tutorial fehlt: ${area}`)
  return module
}

export function foundationCount(area: AreaId): number {
  return foundationModule(area).steps.length
}

export const tutorialModule = foundationModule
export const tutorialCount = foundationCount
